// Packs Phosphor "fill" icons (MIT) and world-atlas 110m countries (ISC) into one script the renderer loads.
const fs = require('fs'), path = require('path'), topo = require('topojson-client');
const dir = 'node_modules/@phosphor-icons/core/assets/fill';
const icons = {};
for (const f of fs.readdirSync(dir)) {
  const svg = fs.readFileSync(path.join(dir, f), 'utf8');
  const ds = [...svg.matchAll(/ d="([^"]+)"/g)].map(m => m[1]);
  if (!ds.length || /<(circle|rect|line|polyline|ellipse)/.test(svg.replace(/<rect width="256" height="256" fill="none"\/>/, ''))) continue;
  icons[f.replace('-fill.svg', '')] = ds.join(' ');
}
// Natural Earth I projection -> normalised x 0..1, y 0..~0.52
const ne = (lon, lat) => { const l = lon * Math.PI / 180, p = lat * Math.PI / 180, p2 = p * p, p4 = p2 * p2;
  const x = l * (0.8707 - 0.131979 * p2 + p4 * (-0.013791 + p4 * (0.003971 * p2 - 0.001529 * p4)));
  const y = p * (1.007226 + p2 * (0.015085 + p4 * (-0.044475 + 0.028874 * p2 - 0.005916 * p4)));
  return [+(0.5 + x / (2 * 2.7366)).toFixed(4), +(0.5 - y / (2 * 2.7366) ).toFixed(4)]; };
const w = JSON.parse(fs.readFileSync('node_modules/world-atlas/countries-110m.json'));
const geo = topo.feature(w, w.objects.countries);
const countries = {};
for (const f of geo.features) {
  const name = f.properties.name; if (!name || name === 'Antarctica') continue;
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  const rings = []; let best = null, bestA = -1;
  for (const poly of polys) {
    const r = poly[0].map(([lo, la]) => ne(lo, la)); rings.push(r);
    const xs = r.map(p => p[0]), ys = r.map(p => p[1]);
    const a = (Math.max(...xs) - Math.min(...xs)) * (Math.max(...ys) - Math.min(...ys));
    if (a > bestA) { bestA = a; best = [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)]; }
  }
  countries[name] = { rings, box: best.map(v => +v.toFixed(4)) };
}
fs.writeFileSync('/home/claude/video-autopilot/engine/everyhow/assets.js',
  `// Generated by prep_assets.js. Icons: Phosphor Icons "fill" set (MIT). Map: world-atlas 110m (ISC), Natural Earth data (public domain).\nwindow.ICONS=${JSON.stringify(icons)};\nwindow.WORLD=${JSON.stringify(countries)};\n`);
fs.writeFileSync('/home/claude/video-autopilot/engine/everyhow/icon_names.txt', Object.keys(icons).join(' '));
