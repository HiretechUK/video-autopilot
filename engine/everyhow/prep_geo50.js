// Packs world-atlas 50m countries (ISC; Natural Earth, public domain) as lon/lat rings for the dark news maps.
const fs = require('fs'), topo = require(process.argv[2] + '/topojson-client');
const w = JSON.parse(fs.readFileSync(process.argv[2] + '/world-atlas/countries-50m.json'));
const out = {};
for (const f of topo.feature(w, w.objects.countries).features) {
  const name = f.properties.name; if (!name || !f.geometry) continue;
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  const rings = []; let best = null, bestA = -1;
  for (const poly of polys) {
    const r = poly[0], un = [r[0].slice()];
    for (const [lo, la] of r.slice(1)) { let l = lo; while (l - un.at(-1)[0] > 180) l -= 360; while (l - un.at(-1)[0] < -180) l += 360; un.push([l, la]); }
    const flat = []; let px = null, py = null;
    for (const [lo, la] of un) { const x = +lo.toFixed(2), y = +la.toFixed(2); if (x === px && y === py) continue; flat.push(x, y); px = x; py = y; }
    if (flat.length < 6) continue; rings.push(flat);
    const xs = un.map(p => p[0]), ys = un.map(p => p[1]), b = [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)];
    const a = (b[2] - b[0]) * (b[3] - b[1]) * Math.cos((b[1] + b[3]) / 2 * Math.PI / 180);
    if (a > bestA) { bestA = a; best = b; }
  }
  if (rings.length) out[name] = { r: rings, b: best.map(v => +v.toFixed(2)) };
}
fs.writeFileSync(process.argv[3], `// Generated by geo50.js from world-atlas 50m (ISC), Natural Earth data (public domain). r: rings as flat lon,lat; b: box of the largest ring.\nwindow.GEO=${JSON.stringify(out)};\n`);
console.log(Object.keys(out).length, 'countries');
